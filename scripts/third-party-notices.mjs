import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Generates THIRD-PARTY-NOTICES.md from installed metadata.
 *
 * Scope is deliberate: direct dependencies only. Transitive packages carry
 * their own license files inside their published tarballs, and a full audit
 * needs a real license scanner rather than a hand-rolled walk. This file
 * exists so the direct surface is reviewable and stale entries are obvious.
 */

const root = fileURLToPath(new URL("../", import.meta.url));

function rustDirect() {
  const raw = execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
    stdio: ["ignore", "pipe", "pipe"],
  });
  const meta = JSON.parse(raw);
  const workspaceMembers = new Set(meta.workspace_members);
  const nodes = new Map(meta.resolve.nodes.map((node) => [node.id, node]));
  const direct = new Set();
  for (const member of workspaceMembers) {
    for (const dependency of nodes.get(member)?.deps ?? []) {
      direct.add(dependency.pkg);
    }
  }
  return meta.packages
    .filter((entry) => !workspaceMembers.has(entry.id) && direct.has(entry.id))
    .map((entry) => ({
      name: entry.name,
      version: entry.version,
      license: entry.license ?? "not declared",
    }))
    .sort((left, right) => left.name.localeCompare(right.name));
}

function workspacePackageDirs() {
  const dirs = [];
  for (const group of ["apps", "packages"]) {
    const groupPath = path.join(root, group);
    if (!existsSync(groupPath)) {
      continue;
    }
    for (const name of readdirSync(groupPath, { withFileTypes: true })) {
      if (name.isDirectory()) {
        dirs.push(path.join(groupPath, name.name));
      }
    }
  }
  return dirs;
}

/** Walks up from a resolved module entry until it finds the package's own manifest. */
function packageRootFor(requireFrom, specifier) {
  let current = path.dirname(requireFrom.resolve(specifier));
  for (let depth = 0; depth < 6; depth += 1) {
    const manifestPath = path.join(current, "package.json");
    if (existsSync(manifestPath)) {
      try {
        const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
        if (manifest.name === specifier) {
          return manifest;
        }
      } catch {
        // A malformed manifest is skipped; the walk continues to the parent.
      }
    }
    const parent = path.dirname(current);
    if (parent === current) {
      return undefined;
    }
    current = parent;
  }
  return undefined;
}

function npmDirect() {
  const seen = new Map();
  for (const dir of workspacePackageDirs()) {
    const manifestPath = path.join(dir, "package.json");
    const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    const requireFrom = createRequire(manifestPath);
    const declared = {
      ...manifest.dependencies,
      ...manifest.optionalDependencies,
      ...manifest.devDependencies,
    };
    for (const specifier of Object.keys(declared)) {
      if (specifier.startsWith("@codecitadel/")) {
        continue;
      }
      if (seen.has(specifier)) {
        continue;
      }
      let resolved;
      try {
        resolved = packageRootFor(requireFrom, specifier);
      } catch {
        resolved = undefined;
      }
      seen.set(specifier, {
        name: specifier,
        version: resolved?.version ?? "not installed",
        license: resolved?.license ?? "not declared",
      });
    }
  }
  return [...seen.values()].sort((left, right) => left.name.localeCompare(right.name));
}

function table(title, rows, kind) {
  const lines = [
    `## ${title}`,
    "",
    `| ${kind} | Version | Declared license |`,
    "| --- | --- | --- |",
    ...rows.map((row) => `| \`${row.name}\` | ${row.version} | ${row.license} |`),
    "",
  ];
  return lines;
}

const rust = rustDirect();
const npm = npmDirect();

const output = [
  "# Third-party notices",
  "",
  "Direct dependencies of CodeCitadel and the license each one declares.",
  "Generated by `node scripts/third-party-notices.mjs` from `cargo metadata` and",
  "the installed npm manifests. Do not edit by hand.",
  "",
  "This list covers **direct** dependencies only. Transitive packages are",
  "included in the published artifacts by their own license terms; a full",
  "transitive audit is still outstanding.",
  "",
  ...table("Rust crates", rust, "Crate"),
  ...table("npm packages", npm, "Package"),
];

writeFileSync(path.join(root, "THIRD-PARTY-NOTICES.md"), output.join("\n"), "utf8");
console.log(`wrote THIRD-PARTY-NOTICES.md: ${rust.length} crate(s), ${npm.length} npm package(s)`);
